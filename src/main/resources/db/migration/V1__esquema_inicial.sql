create table appointment (
    id bigint generated by default as identity,
    duration_minutes integer not null,
    price numeric(10,2),
    scheduled_date date not null,
    scheduled_time time(0) not null,
    cancelled_at timestamp(6) with time zone,
    client_id bigint not null,
    completed_at timestamp(6) with time zone,
    confirmed_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    professional_id bigint not null,
    service_id bigint not null,
    updated_at timestamp(6) with time zone,
    status varchar(20) not null check ((status in ('PENDING','CONFIRMED','CANCELLED','COMPLETED','NO_SHOW'))),
    notes varchar(500),
    primary key (id)
);

create table appointment_reminder (
    id bigint generated by default as identity,
    appointment_id bigint not null unique,
    responded_at timestamp(6) with time zone,
    sent_at timestamp(6) with time zone not null,
    response varchar(20) check ((response in ('CONFIRMED','CANCELLED'))),
    status varchar(20) not null check ((status in ('SENT','FAILED'))),
    primary key (id)
);

create table brand (
    id bigint generated by default as identity,
    state varchar(2) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    city varchar(100) not null,
    slug varchar(100) not null unique,
    address varchar(255),
    name varchar(255) not null,
    primary key (id)
);

create table client (
    id bigint generated by default as identity,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    phone varchar(20) not null unique,
    name varchar(255),
    primary key (id)
);

create table client_session (
    id bigint generated by default as identity,
    otp_code varchar(6) not null,
    client_id bigint not null,
    created_at timestamp(6) with time zone not null,
    last_login_at timestamp(6) with time zone,
    otp_expires_at timestamp(6) with time zone not null,
    otp_verified_at timestamp(6) with time zone,
    session_expires_at timestamp(6) with time zone,
    session_token uuid unique,
    primary key (id)
);

create table professional (
    id bigint generated by default as identity,
    is_active boolean not null,
    brand_id bigint not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    phone varchar(20),
    bio varchar(500),
    photo_url varchar(500),
    name varchar(255) not null,
    primary key (id)
);

create table professional_block (
    id bigint generated by default as identity,
    created_at timestamp(6) with time zone not null,
    end_datetime timestamp(6) not null,
    professional_id bigint not null,
    start_datetime timestamp(6) not null,
    reason varchar(500),
    primary key (id)
);

create table professional_photo (
    id bigint generated by default as identity,
    professional_id bigint not null unique,
    updated_at timestamp(6) with time zone not null,
    content_type varchar(50) not null,
    content bytea not null,
    primary key (id)
);

create table professional_schedule (
    id bigint generated by default as identity,
    end_time time(0) not null,
    start_time time(0) not null,
    created_at timestamp(6) with time zone not null,
    professional_id bigint not null,
    updated_at timestamp(6) with time zone,
    day_of_week varchar(9) not null check ((day_of_week in ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY'))),
    primary key (id)
);

create table professional_session (
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    professional_user_id bigint not null,
    token uuid not null,
    primary key (token)
);

create table professional_user (
    id bigint generated by default as identity,
    is_active boolean not null,
    created_at timestamp(6) with time zone not null,
    last_login_at timestamp(6) with time zone,
    professional_id bigint not null unique,
    updated_at timestamp(6) with time zone,
    email varchar(255) not null unique,
    password_hash varchar(255) not null,
    primary key (id)
);

create table service (
    id bigint generated by default as identity,
    duration_minutes integer not null,
    is_active boolean not null,
    price numeric(10,2) not null,
    created_at timestamp(6) with time zone not null,
    professional_id bigint not null,
    updated_at timestamp(6) with time zone,
    description varchar(500),
    name varchar(255) not null,
    primary key (id)
);

create table waiting_list (
    id bigint generated by default as identity,
    offered_date date,
    offered_time time(0),
    preferred_date_end date not null,
    preferred_date_start date not null,
    client_id bigint not null,
    created_at timestamp(6) with time zone not null,
    notified_at timestamp(6) with time zone,
    professional_id bigint not null,
    service_id bigint not null,
    updated_at timestamp(6) with time zone,
    preferred_period varchar(20) check ((preferred_period in ('MORNING','AFTERNOON','EVENING'))),
    status varchar(20) not null check ((status in ('WAITING','NOTIFIED','CANCELLED'))),
    primary key (id)
);

